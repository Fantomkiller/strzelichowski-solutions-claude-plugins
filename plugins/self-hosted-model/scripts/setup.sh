#!/bin/bash
# Sets up Claude Code on a self-hosted OpenAI-compatible model for one folder in your home directory.
# Usage: setup.sh <base-url> <main-model> [simple-model] [folder-name]
# Safe to run again: it repairs and updates what is there. macOS only.
set -euo pipefail
umask 077

BASE_URL="${1:-}"
MAIN="${2:-}"
SIMPLE="${3:-$MAIN}"
FOLDER_NAME="${4:-AI-private}"
PLUGIN_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONF="$HOME/.config/self-hosted-model"
DATA="$HOME/.local/share/self-hosted-model"
FOLDER="$HOME/$FOLDER_NAME"
PORT="${SHM_PORT:-4000}"
PROXY="http://127.0.0.1:$PORT"
LABEL="${SHM_LABEL:-com.strzelichowski.self-hosted-model}"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LITELLM_VERSION="1.102.1"

step() { printf '\n==> %s\n' "$1"; }
fail() { printf '\nERROR: %s\n' "$1" >&2; exit 1; }

[ "$(uname)" = "Darwin" ] || fail "macOS only"
[[ "$BASE_URL" =~ ^https?://[^[:space:]]+$ ]] || fail "usage: setup.sh <base-url> <main-model> [simple-model] [folder-name]"
[[ "$MAIN" =~ ^[A-Za-z0-9._:/@-]+$ ]] || fail "invalid main model id: '$MAIN'"
[[ "$SIMPLE" =~ ^[A-Za-z0-9._:/@-]+$ ]] || fail "invalid simple model id: '$SIMPLE'"
[[ "$FOLDER_NAME" =~ ^[A-Za-z0-9._-]+$ ]] || fail "folder name may use only letters, digits, dot, dash and underscore"
BASE_URL="${BASE_URL%/}"

step "1/7 uv"
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
if ! command -v uv >/dev/null; then
  if command -v brew >/dev/null; then brew install uv
  else curl -LsSf https://astral.sh/uv/install.sh | sh; fi
fi
UV="$(command -v uv)" || fail "could not install uv"

step "2/7 LiteLLM $LITELLM_VERSION"
"$UV" tool install --quiet --force --python 3.12 "litellm[proxy]==$LITELLM_VERSION"
LITELLM="$("$UV" tool dir --bin)/litellm"
[ -x "$LITELLM" ] || fail "missing $LITELLM"

step "3/7 Python for Word and Excel"
mkdir -p "$DATA/bin"
"$UV" venv --quiet --allow-existing --python 3.12 "$DATA/py"
"$UV" pip install --quiet --python "$DATA/py/bin/python" \
  openpyxl==3.1.5 python-docx==1.1.2 pandas==2.2.3 xlrd==2.0.1
PY="$DATA/py/bin/python"
{ echo "#!$PY"; tail -n +2 "$PLUGIN_ROOT/scripts/read-office"; } > "$DATA/bin/read-office"
chmod 755 "$DATA/bin/read-office"

step "4/7 API key"
mkdir -p "$CONF"
if [ -n "${SHM_API_KEY:-}" ]; then
  KEY="$SHM_API_KEY"
elif [ -s "$CONF/api-key" ] && [ "${SHM_NEW_KEY:-0}" != "1" ]; then
  KEY="$(cat "$CONF/api-key")"
else
  # A dialog keeps the key out of the chat and out of the shell history.
  KEY="$(osascript -e "text returned of (display dialog \"Paste the API key for $BASE_URL\" default answer \"\" with hidden answer with title \"Self-hosted model\")" 2>/dev/null)" || KEY=""
  if [ -z "$KEY" ] && [ -t 0 ]; then read -rsp "API key: " KEY; echo; fi
fi
[ -n "$KEY" ] || fail "no API key (dialog cancelled)"
MODELS="$(curl -s -m 30 -w '\n%{http_code}' -H "Authorization: Bearer $KEY" "$BASE_URL/models")" || fail "cannot reach $BASE_URL"
[ "$(tail -n1 <<<"$MODELS")" = "200" ] || fail "the server refused the key ($BASE_URL/models: HTTP $(tail -n1 <<<"$MODELS"))"
sed '$d' <<<"$MODELS" | "$PY" -c '
import json, sys
ids = {m.get("id") for m in json.load(sys.stdin).get("data", [])}
missing = [m for m in sys.argv[1:] if m not in ids]
if missing:
    sys.exit("model not on the server: " + ", ".join(missing))
' "$MAIN" "$SIMPLE" || fail "check the model ids"
printf '%s' "$KEY" > "$CONF/api-key"
unset KEY MODELS
[ -s "$CONF/master-key" ] || printf 'sk-%s' "$(openssl rand -hex 24)" > "$CONF/master-key"
MASTER_KEY="$(cat "$CONF/master-key")"
echo "ok, key accepted, both models found"

step "5/7 Proxy service"
{
  echo "# Generated by self-hosted-model setup. Only these models are reachable; there are no fallbacks."
  echo "model_list:"
  for M in $(printf '%s\n' "$MAIN" "$SIMPLE" | awk '!seen[$0]++'); do
    cat <<EOF
  - model_name: "$M"
    litellm_params:
      model: "hosted_vllm/$M"
      api_base: "$BASE_URL"
      api_key: os.environ/SHM_API_KEY
      additional_drop_params: ["reasoning_effort"]
EOF
  done
  cat <<'EOF'
general_settings:
  master_key: os.environ/LITELLM_MASTER_KEY
litellm_settings:
  drop_params: true
  request_timeout: 600
  telemetry: false
EOF
} > "$CONF/litellm.yaml"

cat > "$DATA/bin/proxy" <<EOF
#!/bin/bash
SHM_API_KEY="\$(cat "$CONF/api-key")"
LITELLM_MASTER_KEY="\$(cat "$CONF/master-key")"
# Local cost map: no download from GitHub on each start.
export SHM_API_KEY LITELLM_MASTER_KEY LITELLM_LOCAL_MODEL_COST_MAP=True LITELLM_LOG=ERROR
exec "$LITELLM" --config "$CONF/litellm.yaml" --host 127.0.0.1 --port $PORT
EOF
chmod 700 "$DATA/bin/proxy"

mkdir -p "$(dirname "$PLIST")"
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>$DATA/bin/proxy</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$DATA/proxy.log</string>
  <key>StandardErrorPath</key><string>$DATA/proxy.log</string>
</dict></plist>
EOF
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
for _ in $(seq 1 10); do lsof -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1 || break; sleep 1; done
lsof -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1 && fail "port $PORT is taken by another program (lsof -iTCP:$PORT)"
launchctl bootstrap "gui/$(id -u)" "$PLIST"
for _ in $(seq 1 90); do curl -sf "$PROXY/health/liveliness" >/dev/null && break; sleep 1; done
curl -sf "$PROXY/health/liveliness" >/dev/null || fail "the proxy did not start, see $DATA/proxy.log"

step "6/7 Test"
REPLY="$(curl -s -m 180 "$PROXY/v1/messages" \
  -H "x-api-key: $MASTER_KEY" -H "anthropic-version: 2023-06-01" -H "content-type: application/json" \
  -d "{\"model\":\"$MAIN\",\"max_tokens\":50,\"messages\":[{\"role\":\"user\",\"content\":\"Reply with one word: works\"}]}")"
grep -q '"type":"text"' <<<"$REPLY" || fail "the model did not answer through the proxy: $(head -c 300 <<<"$REPLY")"
echo "ok, $MAIN answers"

step "7/7 Folder $FOLDER"
mkdir -p "$FOLDER/results" "$FOLDER/.claude"
chmod 700 "$FOLDER"
[ -f "$FOLDER/CLAUDE.md" ] || sed "s#__DATA__#$DATA#g" "$PLUGIN_ROOT/templates/CLAUDE.md" > "$FOLDER/CLAUDE.md"
cat > "$FOLDER/.claude/settings.local.json" <<EOF
{
  "env": {
    "ANTHROPIC_BASE_URL": "$PROXY",
    "ANTHROPIC_AUTH_TOKEN": "$MASTER_KEY",
    "ANTHROPIC_MODEL": "$MAIN",
    "ANTHROPIC_DEFAULT_OPUS_MODEL": "$MAIN",
    "ANTHROPIC_DEFAULT_SONNET_MODEL": "$MAIN",
    "ANTHROPIC_DEFAULT_HAIKU_MODEL": "$SIMPLE",
    "CLAUDE_CODE_SUBAGENT_MODEL": "$MAIN",
    "CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY": "1",
    "CLAUDE_CODE_MAX_OUTPUT_TOKENS": "16000",
    "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC": "1",
    "DISABLE_TELEMETRY": "1",
    "ENABLE_CLAUDEAI_MCP_SERVERS": "false"
  },
  "model": "$MAIN",
  "permissions": {
    "deny": ["WebFetch", "WebSearch"]
  }
}
EOF
printf 'SHM_FOLDER="%s"\nSHM_PROXY="%s"\nSHM_LABEL="%s"\n' "$FOLDER" "$PROXY" "$LABEL" > "$CONF/guard.env"

printf '\nDONE. Folder: %s\n' "$FOLDER"
